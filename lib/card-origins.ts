export function cardOrigin(card: OriginCard): CardOrigin {
  if (card.arcana !== 'minor') return majorOrigins[card.id] || majorOrigins[0];

  const suit = card.suit || 'wands';
  const rank = card.rank || '一';
  const isCourt = ['侍从', '骑士', '王后', '国王'].includes(rank);
  return {
    period: '15世纪花色传统 · 1909年场景重构',
    historicalName: `${card.suitLabel || ''}${rank}／${card.name}`,
    confidence: '韦特重构',
    origin: `${suitOrigins[suit]}${isCourt ? '宫廷牌的身份等级来自欧洲纸牌中的侍从、骑士、王后与国王。' : `早期这张数字牌通常只展示${rank}个花色标记，并没有统一的人物故事。`}`,
    waiteSmith: `${minorScenes[suit][rank]}现有资料并未为这幅具体场景留下唯一、逐项可证的文字出处，因此应视为 Smith 的艺术重构，而非15世纪原始牌义。`,
  };
}
